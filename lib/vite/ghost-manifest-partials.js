/**
 * Vite plugin: turn the build manifest into static Handlebars partials.
 *
 * Ghost renders templates and cannot read `manifest.json` at render time, and
 * Vite hashes output filenames. So the mapping logical entry -> hashed file is
 * resolved here, at build time, and written into partials that the templates
 * include with `{{> "vite_assets/head"}}` / `{{> "vite_assets/foot"}}`.
 *
 * The partials are committed so a fresh clone parses before the first build.
 * They are regenerated on every build; never edit them by hand.
 *
 * @param {string} manifestPath  Vite manifest, relative to the project root
 * @param {string} headPath      generated partial for <head>
 * @param {string} footPath      generated partial for before </body>
 */
import fs from "node:fs";
import path from "node:path";

const BANNER = "{{!-- Generated by lib/vite/ghost-manifest-partials.js — do not edit. --}}";

export default function ghostManifestPartials(
  manifestPath = "assets/built/manifest.json",
  headPath = "partials/vite_assets/head.hbs",
  footPath = "partials/vite_assets/foot.hbs",
) {
  return {
    name: "ghost-manifest-partials",
    apply: "build",

    closeBundle() {
      if (!fs.existsSync(manifestPath)) {
        this.error(`${manifestPath} not found — the build produced no manifest, so the theme would ship unstyled`);
      }

      const manifest = JSON.parse(fs.readFileSync(manifestPath, "utf8"));

      // ONLY static entries. Dynamic chunks (code-split islands and the framework
      // they pull in) must never be preloaded or eager-loaded here: they are
      // fetched by the island runtime when a mount point actually exists, which is
      // what keeps React off pages that have no islands.
      const entries = Object.values(manifest).filter((entry) => entry.isEntry && entry.file?.endsWith(".js"));

      if (!entries.length) {
        this.error(`${manifestPath} contains no isEntry JS chunk — check build.rollupOptions.input`);
      }

      const head = [BANNER];
      const foot = [BANNER];
      let stylesheets = 0;

      for (const entry of entries) {
        // Static imports of the entry are part of the critical path; the entry
        // also imports them itself, so preloading only shortens the waterfall.
        for (const key of entry.imports ?? []) {
          const chunk = manifest[key];
          if (chunk?.file) head.push(`<link rel="modulepreload" href="{{asset "built/${chunk.file}"}}">`);
        }
        for (const css of entry.css ?? []) {
          // Ghost's {{asset}} adds its own ?v= hash on top of Vite's content hash; both are wanted.
          head.push(`<link rel="stylesheet" href="{{asset "built/${css}"}}">`);
          stylesheets++;
        }
        head.push(`<link rel="modulepreload" href="{{asset "built/${entry.file}"}}">`);
        foot.push(`<script type="module" src="{{asset "built/${entry.file}"}}"></script>`);
      }

      if (!stylesheets) {
        this.error("the entry emitted no CSS — Tailwind would silently produce an unstyled theme");
      }

      for (const [file, lines] of [
        [headPath, head],
        [footPath, foot],
      ]) {
        fs.mkdirSync(path.dirname(file), { recursive: true });
        fs.writeFileSync(file, `${lines.join("\n")}\n`, "utf8");
        this.warn(`${file} updated (${lines.length - 1} tag(s))`);
      }
    },
  };
}
